"""Encrypted file store (trust boundary TB2).

Files are written only as ciphertext, under random 64-hex-character names
generated by the server. User-supplied names never reach the filesystem, and
every resolved path is checked to stay inside the storage directory.
"""
from __future__ import annotations

import os
import re
import secrets
from pathlib import Path

from flask import current_app

from ..extensions import db
from ..models import IntegrityStatus, StoredFile, utcnow
from ..security.crypto import CryptoService, IntegrityError
from ..security.validation import ValidatedUpload

_STORAGE_NAME_RE = re.compile(r"^[0-9a-f]{64}$")


class StorageError(RuntimeError):
    pass


def _crypto() -> CryptoService:
    return current_app.extensions["securevault_crypto"]


def storage_dir() -> Path:
    return Path(current_app.config["STORAGE_DIR"])


def _path_for(storage_name: str) -> Path:
    if not _STORAGE_NAME_RE.fullmatch(storage_name):
        raise StorageError("invalid storage name")
    base = storage_dir().resolve()
    path = (base / f"{storage_name}.enc").resolve()
    if path.parent != base:  # defence in depth against traversal
        raise StorageError("path escapes storage directory")
    return path


def save_encrypted(owner_id: int, upload: ValidatedUpload) -> StoredFile:
    storage_name = secrets.token_hex(32)
    enc = _crypto().encrypt_file(upload.data, storage_name, owner_id)
    path = _path_for(storage_name)
    path.parent.mkdir(parents=True, exist_ok=True)

    # O_EXCL guarantees we never overwrite an existing object.
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0), 0o600)
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(enc.ciphertext)
    except Exception:
        path.unlink(missing_ok=True)
        raise

    record = StoredFile(
        owner_id=owner_id,
        original_name=upload.display_name,
        storage_name=storage_name,
        extension=upload.extension,
        mime_type=upload.mime_type,
        size_bytes=len(upload.data),
        sha256=enc.sha256,
        file_nonce=enc.file_nonce,
        wrapped_dek=enc.wrapped_dek,
        dek_nonce=enc.dek_nonce,
        key_version=_crypto().key_version,
        integrity_status=IntegrityStatus.VERIFIED.value,
        last_verified_at=utcnow(),
    )
    try:
        db.session.add(record)
        db.session.commit()
    except Exception:
        db.session.rollback()
        path.unlink(missing_ok=True)
        raise
    return record


def read_and_verify(record: StoredFile) -> bytes:
    """Decrypt and verify a file. Raises IntegrityError on any failure."""
    try:
        ciphertext = _path_for(record.storage_name).read_bytes()
    except (OSError, StorageError) as exc:
        raise IntegrityError("ciphertext_missing") from exc
    return _crypto().decrypt_and_verify(
        ciphertext,
        file_nonce=record.file_nonce,
        wrapped_dek=record.wrapped_dek,
        dek_nonce=record.dek_nonce,
        storage_name=record.storage_name,
        owner_id=record.owner_id,
        key_version=record.key_version,
        expected_sha256=record.sha256,
    )


def verify(record: StoredFile) -> tuple[bool, str | None]:
    """Verify a file and persist its integrity status. Returns (ok, reason)."""
    try:
        read_and_verify(record)
        ok, reason = True, None
    except IntegrityError as exc:
        ok, reason = False, exc.reason
    record.integrity_status = (IntegrityStatus.VERIFIED if ok else IntegrityStatus.FAILED).value
    record.last_verified_at = utcnow()
    db.session.commit()
    return ok, reason


def delete(record: StoredFile) -> None:
    """Delete ciphertext and metadata.

    Removing the wrapped DEK from the database is a form of crypto-shredding:
    even if the ciphertext survives on disk (e.g. SSD wear levelling or a
    backup), it can no longer be decrypted.
    """
    try:
        path = _path_for(record.storage_name)
    except StorageError:
        path = None
    db.session.delete(record)
    db.session.commit()
    if path is not None:
        path.unlink(missing_ok=True)
